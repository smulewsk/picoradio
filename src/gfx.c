uint16_t g_fb[TFT_WIDTH * TFT_HEIGHT];

static SemaphoreHandle_t s_fb_lock;
void gfx_lock_init(void) { s_fb_lock = xSemaphoreCreateMutex(); }
void gfx_lock(void)   { if (s_fb_lock) xSemaphoreTake(s_fb_lock, portMAX_DELAY); }
void gfx_unlock(void) { if (s_fb_lock) xSemaphoreGive(s_fb_lock); }

