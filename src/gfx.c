void gfx_clear(uint16_t color) {
    for (int i = 0; i < TFT_WIDTH * TFT_HEIGHT; i++) g_fb[i] = color;
}

void gfx_fill(int x, int y, int w, int h, uint16_t color) {
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y;
    int x1 = x + w > TFT_WIDTH ? TFT_WIDTH : x + w;
    int y1 = y + h > TFT_HEIGHT ? TFT_HEIGHT : y + h;
    for (int yy = y0; yy < y1; yy++) {
        uint16_t *row = &g_fb[yy * TFT_WIDTH];
        for (int xx = x0; xx < x1; xx++) row[xx] = color;
    }
}

void gfx_rect(int x, int y, int w, int h, uint16_t color) {
    gfx_fill(x, y, w, 1, color);
    gfx_fill(x, y + h - 1, w, 1, color);
    gfx_fill(x, y, 1, h, color);
    gfx_fill(x + w - 1, y, 1, h, color);
}

int gfx_text_width(const char *s, int scale) {
    return (int)strlen(s) * 6 * scale;
}

int gfx_text(int x, int y, const char *s, uint16_t color, int scale, const clip_t *clip) {
    clip_t full = { 0, 0, TFT_WIDTH, TFT_HEIGHT };
    clip_t c = clip ? *clip : full;
    if (c.x0 < 0) c.x0 = 0;
    if (c.y0 < 0) c.y0 = 0;
    if (c.x1 > TFT_WIDTH) c.x1 = TFT_WIDTH;
    if (c.y1 > TFT_HEIGHT) c.y1 = TFT_HEIGHT;

    for (; *s; s++, x += 6 * scale) {
        if (x >= c.x1) break;
        if (x + 5 * scale <= c.x0) continue;
        unsigned ch = (unsigned char)*s;
        if (ch < 0x20 || ch > 0x7E) ch = '?';
        const uint8_t *g = FONT5X7[ch - 0x20];
        for (int col = 0; col < 5; col++) {
            uint8_t bits = g[col];
            for (int row = 0; row < 7; row++) {
                if (!(bits & (1u << row))) continue;
                for (int dy = 0; dy < scale; dy++) {
                    int py = y + row * scale + dy;
                    if (py < c.y0 || py >= c.y1) continue;
                    for (int dx = 0; dx < scale; dx++) {
                        int px = x + col * scale + dx;
                        if (px >= c.x0 && px < c.x1) g_fb[py * TFT_WIDTH + px] = color;
                    }
                }
            }
        }
    }
    return x;
}
