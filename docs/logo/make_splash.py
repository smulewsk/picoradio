#!/usr/bin/env python3
"""Converts the logo into the TFT boot splash (src/splash_logo.h).

    python3 docs/logo/make_splash.py            (macOS: uses qlmanage + sips)

Renders logo.svg, scales it to SPLASH_W pixels wide, composites it on black,
dithers to RGB565 and writes it in the panel's byte order, ready to copy
into the framebuffer.
"""
import os, sys, subprocess, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SPLASH_W = 268
BG = (0, 0, 0)                        # TFT background (C_BG)

from export_png import read_png, write_png, render

def rle(words):
    """Runs of 3+ equal pixels -> (0x8000 | n, colour); the rest -> (n, pixels...)."""
    out, lit, i = [], [], 0
    def flush():
        while lit:
            chunk = lit[:32767]
            del lit[:32767]
            out.append(len(chunk))
            out.extend(chunk)
    while i < len(words):
        j = i
        while j < len(words) and words[j] == words[i] and j - i < 32767:
            j += 1
        if j - i >= 3:
            flush()
            out += [0x8000 | (j - i), words[i]]
            i = j
        else:
            lit.append(words[i])
            i += 1
    flush()
    return out

def main():
    svg = os.path.join(HERE, 'logo.svg')
    with tempfile.TemporaryDirectory() as t:
        w, h, px = render(svg, 2048, '#%02x%02x%02x' % BG)   # on the TFT background colour
        big = os.path.join(t, 'big.png')
        write_png(big, w, h, px)
        small = os.path.join(t, 'small.png')
        subprocess.run(['sips', '--resampleWidth', str(SPLASH_W), big, '--out', small], check=True, capture_output=True)
        w, h, px = read_png(small)

    bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    words = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[(y * w + x) * 4:(y * w + x) * 4 + 4]
            r = (r * a + BG[0] * (255 - a)) // 255
            g = (g * a + BG[1] * (255 - a)) // 255
            b = (b * a + BG[2] * (255 - a)) // 255
            d = (bayer[y & 3][x & 3] - 7.5) / 16.0       # ordered dither, +-half a step
            r5 = max(0, min(31, round(r / 255 * 31 + d)))
            g6 = max(0, min(63, round(g / 255 * 63 + d)))
            b5 = max(0, min(31, round(b / 255 * 31 + d)))
            c = (r5 << 11) | (g6 << 5) | b5
            words.append(((c >> 8) | (c << 8)) & 0xFFFF)   # panel byte order (see gfx.h rgb())

    codes = rle(words)
    out = os.path.join(ROOT, 'src', 'splash_logo.h')
    with open(out, 'w') as f:
        f.write('/* Boot splash: docs/logo/logo.svg as RGB565 (panel byte order), run-length coded.\n'
                ' * Generated by docs/logo/make_splash.py - do not edit.\n'
                ' * Stream of 16-bit words: header with bit 15 set = run of (header & 0x7fff)\n'
                ' * copies of the next word; bit 15 clear = that many literal pixels follow. */\n'
                '#pragma once\n#include <stdint.h>\n\n')
        f.write(f'#define SPLASH_W {w}\n#define SPLASH_H {h}\n\nstatic const uint16_t SPLASH_RLE[{len(codes)}] = {{\n')
        for i in range(0, len(codes), 12):
            f.write('    ' + ', '.join(f'0x{v:04x}' for v in codes[i:i + 12]) + ',\n')
        f.write('};\n')
    print(f'{out}: {w}x{h}, {len(words) * 2} bytes -> {len(codes) * 2} bytes RLE')

if __name__ == '__main__':
    main()
